// ------------------------------------------------------------------ web chat

const color = z.string().regex(/^#[0-9a-fA-F]{6}$/, 'Use a hex colour');
const origin = z
  .string()
  .trim()
  .max(200)
  .refine((v) => {
    try {
      const u = new URL(v);
      return (
        (u.protocol === 'https:' || u.protocol === 'http:') && u.origin === v.replace(/\/$/, '')
      );
    } catch {
      return false;
    }
  }, 'Use a site address such as https://example.com')
  .transform((v) => v.replace(/\/$/, ''));

export const webchatConfigSchema = z.object({
  color: color.default('#16a34a'),
  title: z.string().trim().min(1).max(60).default('Chat with us'),
  greeting: z.string().trim().max(500).default('Hi! How can we help?'),
  /** Ask for a name and email before the first message. */
  askDetails: z.boolean().default(false),
  /** Sites allowed to embed the widget. Empty allows any site. */
  allowedOrigins: z.array(origin).max(20).default([]),
});
export type WebchatConfig = z.infer<typeof webchatConfigSchema>;

export const createWebchatSchema = z.object({
  name: z.string().trim().min(1).max(80),
  config: webchatConfigSchema.partial().default({}),
});
export type CreateWebchatInput = z.input<typeof createWebchatSchema>;

export const updateChannelSchema = z.object({
  name: z.string().trim().min(1).max(80).optional(),
  config: webchatConfigSchema.partial().optional(),
});
export type UpdateChannelInput = z.infer<typeof updateChannelSchema>;

/** What the widget sends. The visitor token comes back from `session`. */
export const webchatSessionSchema = z.object({
  /** A token from an earlier session, to keep the same conversation. */
  token: z.string().max(300).optional(),
  /** The page embedding the widget, as the browser reports it. */
  origin: z.string().max(300).optional(),
});

export const webchatMessageSchema = z.object({
  token: z.string().min(10).max(300),
  /** Generated by the widget, so a retried send is stored once. */
  clientMessageId: z.uuid(),
  body: z.string().trim().min(1, 'Message is empty').max(2000),
  name: z.string().trim().max(80).optional(),
  email: z.email().max(254).optional(),
  /** A button the visitor tapped, from a flow. */
  replyId: z.string().max(200).optional(),
});
export type WebchatMessageInput = z.infer<typeof webchatMessageSchema>;

export const webchatReadSchema = z.object({ token: z.string().min(10).max(300) });

export interface WebchatSessionDto {
  token: string;
  channel: { name: string } & Pick<WebchatConfig, 'color' | 'title' | 'greeting' | 'askDetails'>;
  /** True once the visitor has written: earlier messages are shown. */
  started: boolean;
}

export interface WebchatMessageDto {
  id: string;
  /** visitor wrote it, agent (or a bot) answered */
  from: 'visitor' | 'agent';
  body: string | null;
  /** Buttons to tap, from a flow. */
  buttons: { id: string; title: string }[];
  senderName: string | null;
  createdAt: string;
}

/** The visitor's room on the /webchat namespace. */
export const webchatRoom = (conversationId: string) => `webchat:${conversationId}`;
export const WEBCHAT_NAMESPACE = '/webchat';

export interface WebchatServerEvents {
  'message:new': (e: { message: WebchatMessageDto }) => void;
}

